import { redact, redactionOptions } from './redact.mjs';

// Markdown rendering only. Deterministic by construction: nothing here reads
// the clock, so re-rendering unchanged data produces byte-identical output and
// the tick can skip the write.

const BANNER = '<!-- generated by worklog — edits here are overwritten on the next tick -->';

function plural(n, word) { return `${n} ${word}${n === 1 ? '' : 's'}`; }

function cite(evidence) {
  const ids = (evidence || []).slice(0, 3);
  return ids.length ? ` \`${ids.join(' ')}\`` : '';
}

function topTools(counts, limit = 4) {
  return Object.entries(counts || {})
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit)
    .map(([t, n]) => `${t}×${n}`)
    .join(', ');
}

function activityLine(stats) {
  if (!stats) return '';
  const parts = [plural(stats.events || 0, 'event')];
  const tools = topTools(stats.tools);
  if (tools) parts.push(tools);
  if (stats.files) parts.push(`${plural(stats.files, 'file')} touched`);
  if (stats.failures) parts.push(`${plural(stats.failures, 'failed call')}`);
  if (stats.sessions) parts.push(plural(stats.sessions, 'session'));
  return parts.join(' · ');
}

function findingBlock(findings, heading = 'Findings') {
  if (!findings?.length) return [];
  const lines = [`**${heading}**`, ''];
  for (const f of findings) {
    const kind = f.kind && f.kind !== 'finding' ? `(${f.kind}) ` : '';
    lines.push(`- ${kind}${f.text}${cite(f.evidence)}`);
  }
  lines.push('');
  return lines;
}

function decisionBlock(decisions) {
  if (!decisions?.length) return [];
  const lines = ['**Decisions**', ''];
  for (const d of decisions) lines.push(`- ${d.text}${cite(d.evidence)}`);
  lines.push('');
  return lines;
}

function rcaBlock(rca) {
  if (!rca || !(rca.symptom || rca.rootCause || rca.fix)) return [];
  const lines = ['**Root cause**', ''];
  if (rca.symptom)   lines.push(`- Symptom: ${rca.symptom}`);
  if (rca.rootCause) lines.push(`- Cause: ${rca.rootCause}`);
  if (rca.fix)       lines.push(`- Fix: ${rca.fix}${cite(rca.evidence)}`);
  lines.push('');
  return lines;
}

/**
 * One day across every work item touched. `entries` is what the tick produced
 * for the day: { key, title, summary, findings, decisions, rca, stats }.
 */
export function renderDaily(day, entries = [], { unattributed = null } = {}) {
  const items = [...entries].sort((a, b) => a.key.localeCompare(b.key));
  const totals = items.reduce((n, i) => n + (i.stats?.events || 0), 0)
    + (unattributed?.events || 0);

  const lines = [`# ${day}`, '', BANNER, ''];
  lines.push(`${plural(items.length, 'work item')} · ${plural(totals, 'recorded event')}`);
  lines.push('');

  if (!items.length && !unattributed?.events) {
    lines.push('No activity recorded for this day.');
    lines.push('');
    return lines.join('\n');
  }

  for (const item of items) {
    lines.push(`## ${item.title ? `${item.key} — ${item.title}` : item.key}`);
    lines.push('');
    if (item.summary) { lines.push(item.summary); lines.push(''); }
    lines.push(...findingBlock(item.findings));
    lines.push(...decisionBlock(item.decisions));
    lines.push(...rcaBlock(item.rca));
    const activity = activityLine(item.stats);
    if (activity) { lines.push(`_${activity}_`); lines.push(''); }
  }

  if (unattributed?.events) {
    lines.push('## Unattributed');
    lines.push('');
    lines.push(`_${activityLine(unattributed)}_`);
    lines.push('');
    lines.push('No work-item key appeared in these events.');
    lines.push('');
  }

  return lines.join('\n');
}

function recentFirst(list, field) {
  return [...(list || [])].sort((a, b) => (b[field] || '').localeCompare(a[field] || ''));
}

/** The rolling note for one work item. Derived entirely from its ticket file. */
export function renderItem(ticket, cfg) {
  const opts = redactionOptions(cfg);
  const t = ticket;
  const lines = [`# ${t.title ? `${t.key} — ${t.title}` : t.key}`, '', BANNER, ''];

  const meta = [];
  if (t.status) meta.push(`**Status** ${t.status}`);
  if (t.firstActive || t.lastActive) {
    meta.push(`**Active** ${t.firstActive || '?'} → ${t.lastActive || '?'} (${plural((t.activeDates || []).length, 'day')})`);
  }
  if (t.repos?.length) meta.push(`**Repos** ${t.repos.join(', ')}`);
  if (t.branches?.length) meta.push(`**Branches** ${t.branches.join(', ')}`);
  if (t.jiraUrl) meta.push(`**Link** ${t.jiraUrl}`);
  if (meta.length) { lines.push(meta.join('  \n')); lines.push(''); }

  if (t.notes) { lines.push(t.notes.trim()); lines.push(''); }

  lines.push(...findingBlock(t.findings));
  lines.push(...decisionBlock(t.decisions));
  lines.push(...rcaBlock(t.rca));

  if (t.commits?.length) {
    lines.push(`**Commits** (${t.commits.length})`, '');
    for (const c of recentFirst(t.commits, 'date').slice(0, 20)) {
      lines.push(`- \`${(c.sha || '').slice(0, 9)}\` ${(c.date || '').slice(0, 10)} ${c.message || ''}`);
    }
    if (t.commits.length > 20) lines.push(`- …and ${t.commits.length - 20} more`);
    lines.push('');
  }

  if (t.prs?.length) {
    lines.push(`**Pull requests** (${t.prs.length})`, '');
    for (const p of t.prs) lines.push(`- #${p.id} [${p.status || '?'}] ${p.title || ''}`);
    lines.push('');
  }

  if (t.docs?.length) {
    lines.push(`**Docs** (${t.docs.length})`, '');
    for (const d of recentFirst(t.docs, 'modified').slice(0, 20)) {
      lines.push(`- ${redact(d.path, opts)}`);
    }
    lines.push('');
  }

  if (t.files?.length) {
    const hot = [...t.files].sort((a, b) => (b.count || 0) - (a.count || 0) || a.path.localeCompare(b.path));
    lines.push(`**Files touched** (${t.files.length})`, '');
    for (const f of hot.slice(0, 15)) lines.push(`- ${redact(f.path, opts)} ×${f.count || 1}`);
    if (hot.length > 15) lines.push(`- …and ${hot.length - 15} more`);
    lines.push('');
  }

  if (t.artifacts?.length) {
    lines.push(`**Commands and queries** (${t.artifacts.length})`, '');
    for (const a of recentFirst(t.artifacts, 'date').slice(0, 15)) {
      lines.push(`- \`${redact(a.body || '', opts).replace(/\s+/g, ' ').slice(0, 160)}\``);
    }
    lines.push('');
  }

  if (t.days?.length) {
    lines.push('**Timeline**', '');
    for (const d of [...t.days].sort((a, b) => b.day.localeCompare(a.day))) {
      const summary = d.used === 'model' && d.summary ? ` — ${d.summary}` : '';
      lines.push(`- **${d.day}** ${activityLine(d.stats)}${summary}`);
    }
    lines.push('');
  } else if (t.activeDates?.length) {
    lines.push('**Days**', '');
    lines.push(t.activeDates.join(', '));
    lines.push('');
  }

  return lines.join('\n');
}
